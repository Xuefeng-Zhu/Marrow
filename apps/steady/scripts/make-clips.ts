/**
 * Generates the seven demo clips in `src/clips/`: synthetic stick figures in the marrow-core
 * fixture format. No camera or personal data is involved. The designed outcomes live in
 * `src/clips/outcomes.ts`.
 *
 * Run from apps/steady:  npm run make-clips
 * A test checks that the committed files equal this script's output.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import type { Fixture } from 'marrow-core';
import { CLIP_IDS, OUTCOMES, type ClipId, type CountOutcome, type RomOutcome, type StanceOutcome } from '../src/clips/outcomes.ts';

// MediaPipe Pose indices (kept local so the script runs under plain Node type stripping).
const I = {
  nose: 0,
  leftEar: 7,
  rightEar: 8,
  mouthLeft: 9,
  mouthRight: 10,
  leftShoulder: 11,
  rightShoulder: 12,
  leftElbow: 13,
  rightElbow: 14,
  leftWrist: 15,
  rightWrist: 16,
  leftHip: 23,
  rightHip: 24,
  leftKnee: 25,
  rightKnee: 26,
  leftAnkle: 27,
  rightAnkle: 28,
} as const;

type Pt = readonly [number, number];
type Side = 'left' | 'right';

const UPPER_ARM = 0.15;
const SHIN = 0.15;
const THIGH = 0.2;
const round = (v: number): number => Math.round(v * 1000) / 1000;

/** Smooth 0..1 ramp between a and b (ms). */
function ramp(ms: number, a: number, b: number): number {
  const x = Math.min(1, Math.max(0, (ms - a) / (b - a)));
  return x * x * (3 - 2 * x);
}

/** A standing figure facing the camera with both arms hanging. Landmarks are `[x, y, z, visibility]`. */
class Figure {
  readonly pts: number[][] = Array.from({ length: 33 }, () => [0.5, 0.12, 0, 0.99]);

  set(i: number, [x, y]: Pt): void {
    this.pts[i] = [x, y, 0, 0.99];
  }

  constructor(dx = 0) {
    this.set(I.nose, [0.5 + dx, 0.12]);
    this.set(I.leftEar, [0.46 + dx, 0.12]);
    this.set(I.rightEar, [0.54 + dx, 0.12]);
    this.set(I.mouthLeft, [0.48 + dx, 0.15]);
    this.set(I.mouthRight, [0.52 + dx, 0.15]);
    this.set(I.leftShoulder, [0.4 + dx, 0.2]);
    this.set(I.rightShoulder, [0.6 + dx, 0.2]);
    this.set(I.leftHip, [0.4 + dx, 0.6]);
    this.set(I.rightHip, [0.6 + dx, 0.6]);
    this.set(I.leftElbow, [0.38 + dx, 0.35]);
    this.set(I.rightElbow, [0.62 + dx, 0.35]);
    this.set(I.leftWrist, [0.38 + dx, 0.5]);
    this.set(I.rightWrist, [0.62 + dx, 0.5]);
    this.set(I.leftKnee, [0.4, 0.8]);
    this.set(I.rightKnee, [0.6, 0.8]);
    this.set(I.leftAnkle, [0.4, 0.95]);
    this.set(I.rightAnkle, [0.6, 0.95]);
    // Eyes sit on the nose. Hands and feet are attached in `finish`.
    for (const i of [1, 2, 3, 4, 5, 6]) this.pts[i] = [...this.pts[I.nose]!];
  }

  /** Attach hands and feet to the wrists and ankles so the overlay has no stray points, then round. */
  finish(): number[][] {
    for (const [i, from] of [
      [17, I.leftWrist],
      [19, I.leftWrist],
      [21, I.leftWrist],
      [18, I.rightWrist],
      [20, I.rightWrist],
      [22, I.rightWrist],
      [29, I.leftAnkle],
      [31, I.leftAnkle],
      [30, I.rightAnkle],
      [32, I.rightAnkle],
    ] as const) {
      this.pts[i] = [...this.pts[from]!];
    }
    return this.pts.map((p) => p.map(round));
  }
}

type Frame = Fixture['frames'][number];

function frames(fps: number, endMs: number, pose: (t: number) => number[][]): Frame[] {
  const step = 1000 / fps;
  const out: Frame[] = [];
  for (let i = 0; i * step <= endMs; i++) {
    const t = i * step;
    out.push({ t, l: pose(t) as Frame['l'] });
  }
  return out;
}

/** One cycle of a ROM clip: rest, raise, hold the peak, lower, rest. */
const ROM_CYCLE_MS = 5000;
const ROM_END_MS = 3 * ROM_CYCLE_MS + 1000;

function romValue(t: number, rest: number, peaks: readonly number[]): number {
  const cycle = Math.min(peaks.length - 1, Math.floor(t / ROM_CYCLE_MS));
  const ms = t - cycle * ROM_CYCLE_MS;
  return rest + (peaks[cycle]! - rest) * (ramp(ms, 1000, 2500) - ramp(ms, 3000, 4500));
}

const rad = (deg: number): number => (deg * Math.PI) / 180;

function shoulderClip(id: ClipId, side: Side, o: RomOutcome): Fixture {
  const sgn = side === 'left' ? -1 : 1;
  const sx = side === 'left' ? 0.4 : 0.6;
  const REST = 12;
  return {
    version: 1,
    id,
    description: `Synthetic ${side} arm raised three times, peaks ${o.peaks.join(', ')} degrees (generated by scripts/make-clips.ts)`,
    fps: o.fps,
    landmarkCount: 33,
    frames: frames(o.fps, ROM_END_MS, (t) => {
      const theta = rad(romValue(t, REST, o.peaks));
      const f = new Figure();
      const dir: Pt = [sgn * Math.sin(theta), Math.cos(theta)];
      f.set(I[`${side}Elbow`], [sx + dir[0] * UPPER_ARM, 0.2 + dir[1] * UPPER_ARM]);
      f.set(I[`${side}Wrist`], [sx + dir[0] * UPPER_ARM * 2, 0.2 + dir[1] * UPPER_ARM * 2]);
      return f.finish();
    }),
  };
}

function kneeClip(id: ClipId, side: Side, o: RomOutcome): Fixture {
  const sgn = side === 'left' ? -1 : 1;
  const kx = side === 'left' ? 0.4 : 0.6;
  const REST_FLEX = 15;
  return {
    version: 1,
    id,
    description: `Synthetic ${side} knee bent three times, deepest flexion ${o.peaks.join(', ')} degrees (generated by scripts/make-clips.ts)`,
    fps: o.fps,
    landmarkCount: 33,
    frames: frames(o.fps, ROM_END_MS, (t) => {
      const flex = rad(romValue(t, REST_FLEX, o.peaks));
      const f = new Figure();
      f.set(I[`${side}Ankle`], [kx + sgn * SHIN * Math.sin(flex), 0.8 + SHIN * Math.cos(flex)]);
      return f.finish();
    }),
  };
}

const STAND_CYCLE_MS = 2600;

function chairClip(id: ClipId, o: CountOutcome): Fixture {
  const SEATED = 90;
  const STANDING = 12; // thigh angle from vertical, so the knee angle is 180 minus this
  const endMs = o.windowMs + 1000;
  return {
    version: 1,
    id,
    description: `Synthetic seated figure standing up ${o.stands} times in 30 seconds (generated by scripts/make-clips.ts)`,
    fps: o.fps,
    landmarkCount: 33,
    frames: frames(o.fps, endMs, (t) => {
      const cycle = Math.floor(t / STAND_CYCLE_MS);
      const ms = t - cycle * STAND_CYCLE_MS;
      const active = cycle < o.stands;
      const psi = rad(
        active ? SEATED + (STANDING - SEATED) * (ramp(ms, 300, 1000) - ramp(ms, 1500, 2200)) : SEATED,
      );
      const f = new Figure();
      const hip: Pt = [0.4, 0.6];
      const knee: Pt = [hip[0] + THIGH * Math.sin(psi), hip[1] + THIGH * Math.cos(psi)];
      f.set(I.leftKnee, knee);
      f.set(I.leftAnkle, [knee[0], knee[1] + SHIN]);
      return f.finish();
    }),
  };
}

function stanceClip(id: ClipId, side: Side, o: StanceOutcome): Fixture {
  const other: Side = side === 'left' ? 'right' : 'left';
  const LIFT = 0.2; // image units, which is 0.5 torso lengths
  const desc =
    o.reason === 'released'
      ? `foot down at ${o.footDownMs! / 1000} s`
      : `sway past the limit from ${o.swayOnsetMs! / 1000} s`;
  return {
    version: 1,
    id,
    description: `Synthetic stance on the ${side} leg, foot lifted at ${o.liftMs / 1000} s, ${desc} (generated by scripts/make-clips.ts)`,
    fps: o.fps,
    landmarkCount: 33,
    frames: frames(o.fps, o.endMs, (t) => {
      const lifted = t >= o.liftMs && (o.footDownMs === undefined || t < o.footDownMs);
      // Small steady wobble of the upper body, well inside the sway limit.
      let dx = 0.015 * Math.sin((2 * Math.PI * t) / 1700);
      if (o.swayOnsetMs !== undefined && t >= o.swayOnsetMs) dx = 0.14;
      const f = new Figure(dx);
      const sx = side === 'left' ? 0.4 : 0.6;
      const ox = other === 'left' ? 0.4 : 0.6;
      f.set(I[`${side}Knee`], [sx, 0.8]);
      f.set(I[`${side}Ankle`], [sx, 0.95]);
      if (lifted) {
        f.set(I[`${other}Knee`], [ox, 0.75]);
        f.set(I[`${other}Ankle`], [ox, 0.95 - LIFT]);
      }
      return f.finish();
    }),
  };
}

export function generateClip(id: ClipId): Fixture {
  const o = OUTCOMES[id];
  switch (id) {
    case 'shoulder-flexion-left':
      return shoulderClip(id, 'left', o as RomOutcome);
    case 'shoulder-flexion-right':
      return shoulderClip(id, 'right', o as RomOutcome);
    case 'knee-flexion-left':
      return kneeClip(id, 'left', o as RomOutcome);
    case 'knee-flexion-right':
      return kneeClip(id, 'right', o as RomOutcome);
    case 'chair-stand':
      return chairClip(id, o as CountOutcome);
    case 'single-leg-stance-left':
      return stanceClip(id, 'left', o as StanceOutcome);
    case 'single-leg-stance-right':
      return stanceClip(id, 'right', o as StanceOutcome);
  }
}

export function generateClips(): Record<ClipId, Fixture> {
  return Object.fromEntries(CLIP_IDS.map((id) => [id, generateClip(id)])) as Record<ClipId, Fixture>;
}

/** Compact JSON: one line per frame. */
export function serializeClip(fx: Fixture): string {
  const head = JSON.stringify({ ...fx, frames: undefined }).slice(0, -1);
  const rows = fx.frames.map((f) => `    ${JSON.stringify(f)}`).join(',\n');
  return `${head},"frames":[\n${rows}\n  ]}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const id of CLIP_IDS) {
    const out = fileURLToPath(new URL(`../src/clips/${id}.json`, import.meta.url));
    writeFileSync(out, serializeClip(generateClip(id)));
    console.log(`wrote ${out}`);
  }
}
