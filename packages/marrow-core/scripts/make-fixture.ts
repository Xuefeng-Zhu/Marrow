/**
 * Generates `fixtures/elbow-cycle-3reps.json`: a synthetic left arm doing 3 bend and extend
 * cycles, for use with `specs/elbow-cycle.json`. No camera or personal data is involved.
 *
 * Run from packages/marrow-core:  npm run make-fixture
 * A test checks that the committed file equals this script's output.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import type { Fixture } from '../src/fixtures/schema.ts';

// MediaPipe Pose indices (kept local so the script runs under plain Node type stripping).
const I = {
  nose: 0,
  leftShoulder: 11,
  rightShoulder: 12,
  leftElbow: 13,
  rightElbow: 14,
  leftWrist: 15,
  rightWrist: 16,
  leftHip: 23,
  rightHip: 24,
  leftKnee: 25,
  rightKnee: 26,
  leftAnkle: 27,
  rightAnkle: 28,
} as const;

const FPS = 20;
const CYCLE_MS = 3000;
const CYCLES = 3;
const EXTENDED = 170;
const BENT = 50;
const FOREARM = 0.2;

/** Smooth 0..1 ramp between a and b (ms). */
function ramp(ms: number, a: number, b: number): number {
  const x = Math.min(1, Math.max(0, (ms - a) / (b - a)));
  return x * x * (3 - 2 * x);
}

/** Elbow angle in degrees at time `ms` within one cycle. */
function angleAt(ms: number): number {
  const down = ramp(ms, 500, 800);
  const up = ramp(ms, 2400, 2700);
  return EXTENDED + (BENT - EXTENDED) * (down - up);
}

/** Elbow x shift away from the torso. The second cycle drifts out while bent. */
function drift(cycle: number, ms: number): number {
  const base = 0.02;
  if (cycle !== 1) return base;
  return base + 0.14 * (ramp(ms, 1000, 1300) - ramp(ms, 2000, 2300));
}

const round = (v: number): number => Math.round(v * 10000) / 10000;

function pose(angleDeg: number, dx: number): number[][] {
  const pts: number[][] = Array.from({ length: 33 }, () => [0.5, 0.5, 0, 0.99]);
  const set = (i: number, x: number, y: number) => {
    pts[i] = [x, y, 0, 0.99];
  };
  set(I.nose, 0.5, 0.12);
  set(I.leftShoulder, 0.4, 0.2);
  set(I.rightShoulder, 0.6, 0.2);
  set(I.leftHip, 0.4, 0.6);
  set(I.rightHip, 0.6, 0.6);
  set(I.leftKnee, 0.4, 0.8);
  set(I.rightKnee, 0.6, 0.8);
  set(I.leftAnkle, 0.4, 0.95);
  set(I.rightAnkle, 0.6, 0.95);
  set(I.rightElbow, 0.64, 0.4);
  set(I.rightWrist, 0.64, 0.6);

  const ex = 0.4 + dx;
  const ey = 0.4;
  set(I.leftElbow, ex, ey);
  // The forearm is the elbow-to-shoulder direction rotated by the elbow angle.
  const ux = 0.4 - ex;
  const uy = 0.2 - ey;
  const len = Math.hypot(ux, uy);
  const rad = (angleDeg * Math.PI) / 180;
  const c = Math.cos(rad);
  const s = Math.sin(rad);
  const rx = (ux / len) * c + (uy / len) * s;
  const ry = -(ux / len) * s + (uy / len) * c;
  set(I.leftWrist, ex + FOREARM * rx, ey + FOREARM * ry);
  return pts.map((p) => p.map(round));
}

export function generateElbowCycleFixture(): Fixture {
  const frameMs = 1000 / FPS;
  const total = CYCLE_MS * CYCLES;
  const frames: Fixture['frames'] = [];
  for (let t = 0; t <= total; t += frameMs) {
    const cycle = Math.min(CYCLES - 1, Math.floor(t / CYCLE_MS));
    const ms = t - cycle * CYCLE_MS;
    frames.push({ t, l: pose(angleAt(ms), drift(cycle, ms)) as Fixture['frames'][number]['l'] });
  }
  return {
    version: 1,
    id: 'elbow-cycle-3reps',
    description: 'Synthetic left arm, 3 bend and extend cycles (generated by scripts/make-fixture.ts)',
    fps: FPS,
    landmarkCount: 33,
    frames,
  };
}

/** Compact JSON: one line per frame. */
export function serializeFixture(fx: Fixture): string {
  const head = JSON.stringify({ ...fx, frames: undefined }).slice(0, -1);
  const rows = fx.frames.map((f) => `    ${JSON.stringify(f)}`).join(',\n');
  return `${head},"frames":[\n${rows}\n  ]}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = fileURLToPath(new URL('../fixtures/elbow-cycle-3reps.json', import.meta.url));
  writeFileSync(out, serializeFixture(generateElbowCycleFixture()));
  console.log(`wrote ${out}`);
}
